"""Render the Markdown audit summary from the audit JSON dict (numbers only, no decisions)."""

from __future__ import annotations


def _p(x, d=1) -> str:
    return "n/a" if x is None else f"{100 * x:.{d}f}%"


def _n(x) -> str:
    return f"{int(x):,}"


def render(R: dict) -> str:
    b0, b1, b2, b3 = R["b0_integrity"], R["b1_entities_music_author"], R["b2_duplicates_and_ties"], R["b3_labels"]
    b4, b56, b7, b8 = R["b4_split_candidates"], R["b5_b6_repeats_catalog"], R["b7_history_length"], R["b8_columns"]
    b9, b10 = R["b9_popularity_drift"], R["b10_cold_video_feasibility"]
    kd, st, rep = b2["key_duplicates"], b2["same_user_same_timestamp"], b2["repeat_interactions"]["all_rows"]
    ent, mus, auth = b1["entities"], b1["music"], b1["author"]
    ref = R["meta"]["reference_split"]
    L = []
    w = L.append

    w("# Dataset Audit Summary (KuaiRand-Pure, standard logs)\n")
    w("Generated by `uv run python -m kuairand_rec.audit.run`. Full numbers: `audit.json`. Inputs are the 2 standard logs, "
      "`user_features_pure.csv`, `video_features_basic_pure.csv` only. **No filtering applied.**\n")
    w("Terminology: *row* = raw log line; *event* = distinct (user_id, video_id, time_ms); "
      "*pair* = distinct (user_id, video_id). Timezone Asia/Shanghai (CST), inferred from `date` agreement "
      f"({_p(b0['date_field_matches_time_ms_cst_share'], 2)} of rows).\n")
    w(f"Split-dependent numbers use a **provisional reference split** (`{ref}`), for audit only. "
      "It is not a protocol decision.\n")
    w(f"Consistency checks: {sum(R['consistency_checks'].values())}/{len(R['consistency_checks'])} passed.\n")
    failed = [k for k, v in R["consistency_checks"].items() if not v]
    if failed:
        w(f"**WARNING: FAILED consistency checks: {failed}. The numbers below are not reliable.**\n")

    w("## 1. Integrity and entities\n")
    a = ent["all_standard_logs"]
    w(f"- Rows {_n(a['rows'])} (file0 {_n(b0['rows_per_file'][0])}, file1 {_n(b0['rows_per_file'][1])}); "
      f"users {_n(a['users'])}, videos {_n(a['videos'])}, authors {_n(a['authors'])}, "
      f"music ids {_n(a['music_ids_nonzero'])} non-zero (+ id 0).")
    w(f"- Metadata: {_n(b0['user_features']['rows'])} users and {_n(b0['video_features']['rows'])} videos, primary keys unique. "
      f"Log rows lacking metadata: users {b0['log_rows_user_missing_in_features']}, "
      f"videos {b0['log_rows_video_missing_in_features']}. Joins are validated many-to-one, so row counts are preserved.")
    ov = b0["file_overlap_window_rows"]
    w(f"- The files overlap in time {ov['window_cst'][0]} to {ov['window_cst'][1]} "
      f"(file0 {ov['file0']} rows, file1 {ov['file1']} rows). Cross-file exact copies: {kd['cross_file_exact_copies']}.")
    w(f"- `hourmin` minus the CST hour of `time_ms` (hours): {b0['hourmin_minus_time_ms_hour_cst']}. "
      "`hourmin` is a coarse bucket; `time_ms` is the reliable timestamp.\n")

    w("## 2. Duplicates, ties, repeats\n")
    w("| class (key = user, video, time_ms) | groups | rows |\n|---|---:|---:|")
    w(f"| single-row keys | {_n(kd['n_key_groups'] - kd['n_multi_row_groups'])} | {_n(kd['n_key_groups'] - kd['n_multi_row_groups'])} |")
    w(f"| exact-duplicate groups (all non-key fields equal, NaN-aware) | {_n(kd['n_exact_dup_groups'])} | {_n(kd['n_rows_in_exact_dup_groups'])} |")
    w(f"| conflict groups (some non-key field differs) | {_n(kd['n_conflict_groups'])} | {_n(kd['n_rows_in_conflict_groups'])} |")
    w(f"\n- Redundant exact copies (rows beyond the first identical one): {_n(kd['n_redundant_exact_rows'])}.")
    w(f"- Fields that differ in conflict groups (number of groups): {kd['conflict_fields']}.")
    w(f"- Same user, same `time_ms`, >1 distinct video: {_n(st['n_groups_multi_item'])} groups, "
      f"{_n(st['n_rows_in_multi_item_groups'])} rows ({_p(st['rows_in_multi_item_groups_share'], 2)} of rows). "
      f"Distinct videos per group: {st['distinct_items_per_multi_group']}.")
    w(f"- Genuine repeats (same pair, distinct timestamps): {_n(rep['n_pairs_repeated'])} of {_n(rep['n_pairs'])} pairs; "
      f"median gap {rep['gap_hours_quantiles'].get('0.5', 0):.1f} h.\n")

    w("## 3. Actions\n")
    r = b3["rates_all_rows"]
    agree = b3["official_long_view_rule_agreement"]
    dz = b3["duration_ms_zero"]
    w(f"- Rates (raw rows): long_view {_p(r['long_view'])}, is_like {_p(r['is_like'], 2)}, is_click {_p(r['is_click'])}. "
      f"Positive rows: long_view {_n(b3['positives_rows']['long_view'])}, is_like {_n(b3['positives_rows']['is_like'])}.")
    w(f"- {_p(b3['share_like_rows_also_long_view'])} of like rows are also long_view.")
    w(f"- Users with at least one positive: long_view {_n(b3['per_user']['users_with_ge1_long_view'])}, "
      f"is_like {_n(b3['per_user']['users_with_ge1_like'])} of {_n(b3['per_user']['users'])}.")
    w(f"- The official long_view rule (kuairand.com) agrees with the label on {_p(agree['duration_gt_0'], 2)} of rows with duration>0, "
      f"and on {_p(agree['duration_eq_0'], 1)} of rows with duration_ms=0. "
      f"duration_ms=0 covers {_n(dz['rows'])} rows on {dz['videos']} videos, all with null metadata duration, "
      f"and their long_view rate is {_p(dz['long_view_rate'])}.")
    mp = agree["official0_label1_profile"]
    w(f"- With duration>0, all mismatches go one way: {_n(mp['rows'])} rows have label 1 while the rule gives 0, "
      f"and {_p(mp['share_duration_le_18s'])} of them are videos of at most 18 s. Shortfall (ms) quantiles: "
      f"{ {k: round(v) for k, v in mp['shortfall_ms_quantiles'].items()} }. **Hypothesis:** a tolerance of about 1 s.")
    w(f"- Like rows with play_time_ms=0: {b3['like_with_play_time_zero']['rows']}.\n")

    w("## 4. Music and author coverage\n")
    m0 = mus["music_id_0"]
    w(f"- `music_id=0`: {m0['videos']} videos, {_n(m0['log_rows'])} log rows. "
      f"music_type values among them: {m0['music_type_values']}. **Hypothesis:** this is a missing-music sentinel. "
      "It is not defined in the official dictionary.")
    w(f"- Non-zero music ids: {_n(ent['metadata']['music_ids_nonzero'])}; shared by >1 video: "
      f"{mus['music_ids_nonzero_shared']} ids covering {mus['videos_on_shared_nonzero_music']} videos. "
      f"Videos-per-id histogram: {mus['videos_per_music_hist_nonzero']}.")
    pc = mus["positive_rows_share_by_music_category"]
    w(f"- Positive rows by music category: long_view {pc['long_view_all']}; is_like {pc['is_like_all']}.")
    w(f"- Authors: {_n(ent['metadata']['authors'])} for {_n(ent['metadata']['videos'])} videos; "
      f"{_n(auth['authors_with_gt1_video'])} authors have >1 video (max {auth['max_videos_per_author']}).\n")

    w("## 5. Candidate temporal splits (70/15/15)\n")
    w("Rule: boundary T; rows with t < T go to the earlier split, rows with t >= T go to the later one. "
      "A single timestamp is never split.\n")
    w("| candidate | T_val (CST) | T_test (CST) | train / val / test rows | val / test users | test lv / like pos |\n|---|---|---|---|---|---|")
    for k, v in b4.items():
        s = v["splits"]
        w(f"| {k} | {v['cuts_cst'][0]} | {v['cuts_cst'][1]} | "
          f"{' / '.join(_p(x['row_share']) for x in s)} | {_n(s[1]['users'])} / {_n(s[2]['users'])} | "
          f"{_n(s[2]['long_view_pos_rows'])} / {_n(s[2]['is_like_pos_rows'])} |")
    w("")

    w("## 6. Re-consumption and catalog (reference split, test positives)\n")
    for a in ("long_view", "is_like"):
        rc, co = b56["reconsumption"][a], b56["catalog_ooc"][a]
        mr = b56["music_repeats"][a]
        w(f"- **{a}**: {_n(rc['test_pos_rows'])} test positive rows. The (user, video) pair was seen in train: "
          f"{_p(rc['share_test_pos_rows_pair_seen_in_train_any'])} (any interaction), "
          f"{_p(rc['share_test_pos_rows_pair_was_train_pos_same_action'])} (as a train positive for this action). "
          f"OOC share by catalog: all-metadata {_p(co['video']['metadata']['test_pos_rows_ooc_share'])}, "
          f"train-interacted {_p(co['video']['train_seen']['test_pos_rows_ooc_share'])}, "
          f"train-positive {_p(co['video']['train_positive']['test_pos_rows_ooc_share'])}. "
          f"Test music positives whose (user, music) was already a train positive: "
          f"{_p(mr['share_test_music_pos_user_music_was_train_pos'])}; of these, only via a *different* video: "
          f"{_p(mr['share_test_music_pos_only_via_other_video'])}.")
    w("")
    cd = b56["catalog_definitions"]
    w("Catalog levels: **metadata** = all ids in `video_features_basic_pure.csv` (for music: every `music_id` "
      "of a metadata video); **train-seen** = ids with at least one reference-train interaction; "
      "**train-positive** = ids with at least one reference-train positive for the action. "
      f"Metadata music ids that never occur in the standard logs: {cd['metadata_music_ids_absent_from_logs']}.\n")
    w("| action | music catalog | size | test pos OOC (all rows) | test pos OOC (music_id != 0 rows) |\n|---|---|---:|---:|---:|")
    for a in ("long_view", "is_like"):
        for k, c in b56["catalog_ooc"][a]["music"].items():
            w(f"| {a} | {k} | {_n(c['catalog_size'])} | {_p(c['test_pos_rows_ooc_share'], 2)} | "
              f"{_p(c['test_pos_rows_nonzero_music_ooc_share'], 2)} |")
    w("")

    w("## 7. History length at prediction time (reference test positives, strict t < prediction time, uncapped)\n")
    w("| action | history source | protocol | n | 0 | 1-5 | 6-20 | >20 | share >=100 |\n|---|---|---|---:|---:|---:|---:|---:|---:|")
    for a in ("long_view", "is_like"):
        for src in ("all_events_dedup", "long_view_pos_events"):
            for proto in ("frozen_at_test_start", "rolling_per_event"):
                h = b7[a][src][proto]
                s = h["bucket_shares"]
                w(f"| {a} | {src} | {proto} | {_n(h['n'])} | {_p(s['0'])} | {_p(s['1-5'])} | {_p(s['6-20'])} | "
                  f"{_p(s['>20'])} | {_p(h['share_ge_100'])} |")
    ti = b7["long_view"]["tie_impact_rolling"]
    w(f"\n- Ties under rolling: {_n(ti['rows_with_other_same_ts_distinct_events'])} of {_n(ti['test_pos_rows'])} "
      "long_view test rows share their exact timestamp with another distinct same-user event, which the strict rule excludes.\n")

    w("## 8. Columns (see `column_profile.csv`)\n")
    w(f"- Constant: {[c for c in ('is_lowactive_period', 'visible_status')]}. "
      f"`is_live_streamer` values: {b8['is_live_streamer_values']} (-124 is presumably 'unavailable').")
    w(f"- `user_active_degree` values outside the official set: {b8['user_active_degree_values_outside_official_set']}.")
    w(f"- One-hot nulls: {b8['onehot_nulls']}.")
    w(f"- `upload_dt` values: {b8['upload_dt_values']}. Videos first seen before upload_dt: "
      f"{b8['videos_first_interaction_before_upload_dt']}.")
    w(f"- Tags: {b8['distinct_tags']} distinct, per-video counts {b8['tags_per_video']}, null {b8['tag_null_videos']}. "
      f"AD videos {b8['ad_videos']} ({_n(b8['ad_log_rows'])} log rows).")
    w("- Snapshot user features (follow, fans, friend, register_days): the snapshot time is undocumented. "
      "These columns are flagged for leakage review in P1.\n")

    w("## 9. Popularity drift (train vs test positives, reference split)\n")
    for a in ("long_view", "is_like"):
        v = b9[a]["video"]
        w(f"- {a} video: Spearman {v['spearman_counts_union']:.3f}, top-50 overlap {_p(v['top50_overlap'], 0)}, "
          f"test positive share on train top-50 {_p(v['test_pos_share_on_train_top50'])}.")
    w("")

    w("## 10. Cold-video feasibility (reference split)\n")
    w(f"- Candidate pool ({b10['pool_definition']}): {_n(b10['pool_videos'])} videos. Shares within the pool: "
      f"the author has another train video {_p(b10['pool_share_author_has_other_train_video'])}; "
      f"non-zero music {_p(b10['pool_share_music_nonzero'])}; "
      f"music shared with another train video {_p(b10['pool_share_music_shared_with_other_train_video'])}.\n")

    w("## Figures\n")
    for f, cap in (("music_videos_per_id.png", "Videos per music_id, and music categories of positives"),
                   ("daily_volume_splits.png", "Daily volume with candidate split boundaries"),
                   ("history_length.png", "History length at prediction time"),
                   ("action_by_tab.png", "Action rates by tab")):
        w(f"- {cap}: `figures/{f}`")
    return "\n".join(L) + "\n"
